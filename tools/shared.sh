function getVersion() {
	# Only run once per batch run
	if [ "$_GET_VERSION_DONE" = "1" ]; then
		return
	fi
	export _GET_VERSION_DONE=1
	export VERSION_BUILD="$(git rev-list --count HEAD)"

	# Get current branch if not set
	: "${BRANCH:="$(git rev-parse --abbrev-ref HEAD)"}"
	export BRANCH

	if [[ "$(git describe --exact-match --tags 2>/dev/null)" = v* ]]; then
		export BRANCH="stable"
	fi

	# Branch names can contain slashes (e.g. feature/foo), which would end up in
	# the version string and output filenames. Keep only characters that are
	# valid in semver build metadata.
	export BRANCH="${BRANCH//[^A-Za-z0-9.-]/-}"

	# jq is used when available; fall back to sed so a plain clone builds without it.
	if command -v jq >/dev/null 2>&1; then
		CUR=$(jq -r .version "${__DIRNAME}/../version.json" 2>/dev/null)
	else
		CUR=$(sed -n 's/.*"version"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' "${__DIRNAME}/../version.json")
	fi
	if [ -z "$CUR" ] || [ "$CUR" = "null" ]; then
		error "Failed to get version from version.json"
	fi
	VER="$(echo $CUR | cut -d- -f1)"
	VERSION_HASH="$(git rev-parse --short=8 HEAD)"
	export VERSION="${VER}+${VERSION_BUILD}-${BRANCH}-${VERSION_HASH}"

	if [ "$BRANCH" = "stable" ]; then
		export HUMAN_VERSION="${VER}"
	else
		export HUMAN_VERSION="${VER}+${VERSION_BUILD}-${BRANCH}-${VERSION_HASH}"
	fi
	export VERSION_MAJOR=$(echo $VER | cut -d. -f1)
	export VERSION_MINOR=$(echo $VER | cut -d. -f2)
	export VERSION_PATCH=$(echo $VER | cut -d. -f3)
}