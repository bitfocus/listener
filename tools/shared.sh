function _white() {
	echo -e "\033[37m$*\033[m"
}

function _bold() {
	echo -e "\033[1m$*\033[m"
}

function _yellow() {
	echo -e "\033[33m$*\033[m"
}

function _red() {
	echo -e "\033[31m$*\033[m"
}

function _blue() {
	echo -e "\033[34m$*\033[m"
}

function log() {
	echo "$(_blue ➤) $*"
}

function error() {
	echo "$(_red ●) $(_bold $*)" >&2
	exit 1
}

function updateVersionFiles() {
	# Only run once per batch run
